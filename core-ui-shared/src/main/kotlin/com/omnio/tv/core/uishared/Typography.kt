package com.omnio.tv.core.uishared

import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.sp

/**
 * Form-factor-neutral typography token shape. Mirrors Material3's
 * display/headline/title/body/label scale so phone (Material3) and TV
 * (androidx.tv.material3) wrappers can each adapt this into their respective
 * MaterialTheme typography type.
 *
 * The default factory [phoneTypography] returns the phone-native Material3
 * scale; TV's wrapper provides a separate factory with TV-tuned sizes (see
 * :app-tv ui/theme/Type.kt).
 */
data class OmnioTypography(
    val displayLarge: TextStyle,
    val displayMedium: TextStyle,
    val displaySmall: TextStyle,
    val headlineLarge: TextStyle,
    val headlineMedium: TextStyle,
    val headlineSmall: TextStyle,
    val titleLarge: TextStyle,
    val titleMedium: TextStyle,
    val titleSmall: TextStyle,
    val bodyLarge: TextStyle,
    val bodyMedium: TextStyle,
    val bodySmall: TextStyle,
    val labelLarge: TextStyle,
    val labelMedium: TextStyle,
    val labelSmall: TextStyle
)

/**
 * Material3 phone-native typography scale.
 * Sizes match the Material3 type-scale spec for phones; intended for the
 * upcoming :app-phone OmnioTheme. TV uses its own factory with larger sizes
 * tuned for arm's-length reading distance.
 */
