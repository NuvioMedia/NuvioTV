package com.nuvio.tv.ui.screens.player

import androidx.media3.common.util.UnstableApi
import androidx.media3.datasource.DataSource
import androidx.media3.datasource.DefaultDataSource
import androidx.media3.datasource.okhttp.OkHttpDataSource
import com.nuvio.tv.core.network.IPv4FirstDns
import okhttp3.OkHttpClient
import okhttp3.HttpUrl.Companion.toHttpUrlOrNull
import java.io.IOException
import java.net.HttpURLConnection
import java.net.URL
import java.security.SecureRandom
import java.security.cert.X509Certificate
import java.util.concurrent.TimeUnit
import javax.net.ssl.HostnameVerifier
import javax.net.ssl.HttpsURLConnection
import javax.net.ssl.SSLContext
import javax.net.ssl.SSLException
import javax.net.ssl.TrustManager
import javax.net.ssl.X509TrustManager

internal object PlayerPlaybackNetworking {
    private const val LOOPBACK_READ_TIMEOUT_SECONDS = 65L

    /** A preview must not weaken TLS or forward addon credentials to a redirect/segment origin. */
    internal fun createTimelineHttpClient(sourceUrl: String, headers: Map<String, String>,
        lifetime: okhttp3.EventListener = okhttp3.EventListener.NONE): OkHttpClient {
        val origin = sourceUrl.toHttpUrlOrNull()
        require(origin != null && origin.username.isEmpty() && origin.password.isEmpty()) { "Invalid preview source" }
        require(headers.size <= 32 && headers.entries.sumOf { it.key.length + it.value.length } <= 16384 &&
            headers.entries.all { (name, value) ->
                name.length in 1..256 && name.all { it in '!'..'~' && it !in "()<>@,;:\\\"/[]?={} " } &&
                    value.length <= 4096 && value.all { it == '\t' || it in ' '..'~' }
            }) { "Invalid preview headers" }
        val suppliedNames = headers.keys + setOf("Authorization", "Cookie", "Proxy-Authorization")
        return OkHttpClient.Builder()
            .eventListener(lifetime)
            .dns(IPv4FirstDns())
            .connectTimeout(4, TimeUnit.SECONDS).readTimeout(4, TimeUnit.SECONDS)
            .writeTimeout(4, TimeUnit.SECONDS).callTimeout(6, TimeUnit.SECONDS)
            .retryOnConnectionFailure(false)
            .addNetworkInterceptor { chain ->
                val request = chain.request()
                val target = request.url
                if (origin.isHttps && !target.isHttps) throw IOException("Insecure preview redirect")
                val sameOrigin = target.scheme == origin.scheme && target.host == origin.host && target.port == origin.port
                val next = request.newBuilder()
                if (sameOrigin) headers.forEach { (name, value) ->
                    if (!name.equals("Range", true)) next.header(name, value)
                } else suppliedNames.forEach { name ->
                    // The seek range is generated by Media3, not an authentication header.
                    if (!name.equals("Range", true)) next.removeHeader(name)
                }
                chain.proceed(next.build())
            }.build()
    }

    @UnstableApi
    internal fun createTimelineDataSourceFactory(context: android.content.Context, url: String, headers: Map<String, String>,
        lifetime: okhttp3.EventListener = okhttp3.EventListener.NONE): DataSource.Factory {
        val http = if (url.toHttpUrlOrNull() != null) {
            OkHttpDataSource.Factory(createTimelineHttpClient(url, headers, lifetime))
                .setUserAgent(PlayerMediaSourceFactory.DEFAULT_USER_AGENT)
        } else {
            // DefaultDataSource handles file/content locally; remote requests still use strict TLS.
            OkHttpDataSource.Factory(OkHttpClient.Builder().eventListener(lifetime).build())
        }
        return DefaultDataSource.Factory(context, http)
    }

    private val trustAllManager = object : X509TrustManager {
        override fun checkClientTrusted(chain: Array<out X509Certificate>?, authType: String?) = Unit

        override fun checkServerTrusted(chain: Array<out X509Certificate>?, authType: String?) = Unit

        override fun getAcceptedIssuers(): Array<X509Certificate> = emptyArray()
    }

    private val playbackHostnameVerifier = HostnameVerifier { _, _ -> true }

    private val sslContext: SSLContext by lazy {
        SSLContext.getInstance("TLS").apply {
            init(null, arrayOf<TrustManager>(trustAllManager), SecureRandom())
        }
    }

    /**
     * Fallback OkHttpClient equipped with trust-all SSL configuration for self-signed
     * or untrusted local media servers (e.g. self-signed WebDAV / Plex / Jellyfin).
     */
    internal val trustAllPlaybackHttpClient: OkHttpClient by lazy {
        val dispatcher = okhttp3.Dispatcher().apply {
            maxRequests = 64
            maxRequestsPerHost = 32
        }
        OkHttpClient.Builder()
            .dispatcher(dispatcher)
            .dns(IPv4FirstDns())
            .eventListenerFactory(PlaybackConnectionEvents)
            .sslSocketFactory(sslContext.socketFactory, trustAllManager)
            .hostnameVerifier(playbackHostnameVerifier)
            .connectTimeout(15, TimeUnit.SECONDS)
            .readTimeout(15, TimeUnit.SECONDS)
            .writeTimeout(15, TimeUnit.SECONDS)
            .followRedirects(true)
            .followSslRedirects(true)
            .retryOnConnectionFailure(true)
            .build()
    }

    /**
     * Primary OkHttpClient using standard system SSL certificates and full SNI support.
     * Includes an automatic fallback to [trustAllPlaybackHttpClient] if an [SSLException]
     * occurs on self-signed local media servers.
     */
    internal val playbackHttpClient: OkHttpClient by lazy {
        val dispatcher = okhttp3.Dispatcher().apply {
            maxRequests = 64
            maxRequestsPerHost = 32
        }
        OkHttpClient.Builder()
            .dispatcher(dispatcher)
            .dns(IPv4FirstDns())
            .eventListenerFactory(PlaybackConnectionEvents)
            .connectTimeout(15, TimeUnit.SECONDS)
            .readTimeout(15, TimeUnit.SECONDS)
            .writeTimeout(15, TimeUnit.SECONDS)
            .followRedirects(true)
            .followSslRedirects(true)
            .retryOnConnectionFailure(true)
            .addInterceptor { chain ->
                val request = chain.request()
                try {
                    chain.proceed(request)
                } catch (e: SSLException) {
                    // Fallback to trust-all client if standard system SSL fails (e.g. self-signed local server)
                    trustAllPlaybackHttpClient.newCall(request).execute()
                }
            }
            .build()
    }

    fun createHttpClient(
        defaultHeaders: Map<String, String> = emptyMap(),
        useLongReadTimeout: Boolean = false
    ): OkHttpClient {
        val builder = playbackHttpClient.newBuilder()
        if (useLongReadTimeout) {
            builder.readTimeout(LOOPBACK_READ_TIMEOUT_SECONDS, TimeUnit.SECONDS)
        }
        if (defaultHeaders.any { it.key.equals("Authorization", ignoreCase = true) }) {
            // OkHttp strips the Authorization header on cross-host redirects.
            // WebDAV servers behind reverse proxies commonly redirect to a
            // different host/port, causing auth to be lost. A network
            // interceptor ensures the header is always present on every
            // outgoing request — same behavior as mpv/curl.
            val authValue = defaultHeaders.entries
                .first { it.key.equals("Authorization", ignoreCase = true) }
                .value
            builder.addNetworkInterceptor { chain ->
                val request = chain.request()
                if (request.header("Authorization") == null) {
                    chain.proceed(
                        request.newBuilder()
                            .header("Authorization", authValue)
                            .build()
                    )
                } else {
                    chain.proceed(request)
                }
            }
        }
        return builder
            .let { NuvioExoPlayerPerformanceHelper.applyNetworkOptimizations(it) }
            .build()
    }

    @UnstableApi
    fun createHttpDataSourceFactory(
        defaultHeaders: Map<String, String> = emptyMap(),
        useLongReadTimeout: Boolean = false
    ): DataSource.Factory {
        val client = createHttpClient(defaultHeaders, useLongReadTimeout)
        val httpFactory = OkHttpDataSource.Factory(client).apply {
            setDefaultRequestProperties(defaultHeaders)
            if (defaultHeaders.none { it.key.equals("User-Agent", ignoreCase = true) }) {
                setUserAgent(PlayerMediaSourceFactory.DEFAULT_USER_AGENT)
            }
        }
        return LoggingDataSourceFactory(httpFactory, "HTTP")
    }

    @UnstableApi
    fun createDataSourceFactory(
        context: android.content.Context,
        defaultHeaders: Map<String, String> = emptyMap()
    ): DataSource.Factory {
        return DefaultDataSource.Factory(context, createHttpDataSourceFactory(defaultHeaders))
    }

    fun openConnection(
        url: String,
        headers: Map<String, String>,
        method: String,
        connectTimeoutMs: Int,
        readTimeoutMs: Int,
        range: String? = null
    ): HttpURLConnection {
        return (URL(url).openConnection() as HttpURLConnection).apply {
            instanceFollowRedirects = true
            connectTimeout = connectTimeoutMs
            readTimeout = readTimeoutMs
            requestMethod = method
            setRequestProperty("User-Agent", headers["User-Agent"] ?: PlayerMediaSourceFactory.DEFAULT_USER_AGENT)
            headers.forEach { (key, value) ->
                if (key.equals("Range", ignoreCase = true)) return@forEach
                if (key.equals("User-Agent", ignoreCase = true)) return@forEach
                setRequestProperty(key, value)
            }
            range?.let { setRequestProperty("Range", it) }
        }
    }
}

/** Per-preview ownership through response-body completion; never tracks main playback calls. */
internal class TimelineCallCancellation : okhttp3.EventListener() {
    private val closed = java.util.concurrent.atomic.AtomicBoolean(false)
    private val calls = java.util.concurrent.ConcurrentHashMap.newKeySet<okhttp3.Call>()
    override fun callStart(call: okhttp3.Call) {
        calls.add(call)
        if (closed.get()) { call.cancel(); calls.remove(call) }
    }
    override fun callEnd(call: okhttp3.Call) { calls.remove(call) }
    override fun callFailed(call: okhttp3.Call, ioe: java.io.IOException) { calls.remove(call) }
    fun cancel() {
        closed.set(true)
        calls.forEach { it.cancel() }
        calls.clear()
    }
}