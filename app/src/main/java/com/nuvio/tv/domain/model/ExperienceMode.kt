package com.nuvio.tv.domain.model

/**
 * Represents the different experience modes for the application.
 * Controls the level of complexity and features available in the UI.
 */
enum class ExperienceMode {
    /**
     * Essential mode with simplified interface and basic features.
     */
    ESSENTIAL,
    /**
     * Advanced mode with full features and customization options.
     */
    ADVANCED
}
